import { stringify } from "yaml";
import type { Config } from "../src/core/types.js";

const GENERATED = "<!-- Generated by scripts/gen-reference.ts at build time. Do not edit. -->";

const fence = (lang: string, body: string) => `\`\`\`${lang}\n${body.trimEnd()}\n\`\`\``;

/** Reference page for the built-in defaults, rendered from DEFAULT_CONFIG so it cannot drift. */
export function renderConfigReference(cfg: Config): string {
  const sections = (["claude", "codex"] as const).map(
    (name) =>
      `## ${name}\n\nCommand: \`${cfg.agents[name].command}\`\n\n${fence("yaml", stringify({ agents: { [name]: cfg.agents[name] } }))}`,
  );
  return [
    GENERATED,
    "# Defaults reference",
    "These are the built-in defaults. `~/.orch/config.yaml` overrides them per key; see [Configuration](/guide/configuration) for what each key means.",
    `Default agent: \`${cfg.defaultAgent}\``,
    "# Agents",
    ...sections,
    "# Context presets\n\nExtra flags per agent that shrink the fixed context of every call. Select one with `context:` in a rule, `orch run --context NAME`, or the MCP `context` parameter. Presets are off unless selected.",
    fence("yaml", stringify({ contexts: cfg.contexts })),
    "# Roles\n\nBuilt-in roles and teams. Select a role with `--role`, a team with `--team`, or a list with `--roles`; a role is one ordinary run with its own prompt, agent, model and context.",
    fence("yaml", stringify({ roles: cfg.roles, teams: cfg.teams, pipeline: cfg.pipeline })),
    "# Routing rules\n\nFirst matching rule wins; no match uses the default agent.",
    fence("yaml", stringify({ rules: cfg.rules })),
    "# Environment variables",
    [
      "- `ORCH_HOME`: state directory (default `~/.orch`)",
      "- `ORCH_CONFIG`: path of the config file (default `$ORCH_HOME/config.yaml`)",
      "- `ORCH_DEPTH`: set by orch on the agents it starts; a value of 1 or more makes `orch` refuse to run (recursion guard)",
    ].join("\n"),
  ].join("\n\n") + "\n";
}

/** CLI reference page, rendered from the same USAGE text the CLI prints. */
export function renderCliReference(usage: string): string {
  return [GENERATED, "# CLI reference", fence("text", usage)].join("\n\n") + "\n";
}
